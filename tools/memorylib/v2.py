def _bounded_text(root: Path, rel: str, limit: int = 7000) -> str:
    path = root / rel
    if not path.exists():
        return f"[missing: {rel}]"
    text = path.read_text(encoding="utf-8", errors="replace")
    return text if len(text) <= limit else text[:limit] + "\n\n[packet truncated at bounded source limit]\n"


def build_context_packets(root: Path) -> dict[str, int]:
    """Build bounded role packets; never recursively loads the vault."""
    output = root / "builder" / "context"
    output.mkdir(parents=True, exist_ok=True)
    counts: dict[str, int] = {}
    for key, (title, paths) in PACKET_SPECS.items():
        pieces = [
            V2_GENERATED_MARKER,
            f"# {title}",
            "",
            "This packet is generated and bounded. Read only the listed canonical records; do not recursively load the vault.",
            "",
            "## Included canonical paths",
            "",
        ]
        pieces.extend(f"- `{path}`" for path in paths)
        for path in paths:
            pieces.extend(["", f"## {path}", "", _bounded_text(root, path)])
        text = "\n".join(pieces).rstrip() + "\n"
        (output / f"{key}.md").write_text(text, encoding="utf-8")
        counts[key] = len(text)
    current = output / "BUILDER_C_MEMORY.md"
    if current.exists():
        (root / "builder" / "CURRENT_CONTEXT_PACKET.md").write_text(current.read_text(encoding="utf-8"), encoding="utf-8")
    return counts


