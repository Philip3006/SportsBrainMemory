from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import tempfile
from typing import Any

EVENT_TYPES = {
    "CEO_DECISION", "PR_MERGED", "WORKSTREAM_STARTED", "WORKSTREAM_COMPLETED",
    "RESEARCH_GATE", "PRODUCTION_VERIFIED", "BLOCKER_OPENED", "BLOCKER_RESOLVED",
    "ARCHITECTURE_CHANGED", "ROLLBACK", "DEFERRED_DEPENDENCY",
}
VERIFIED_STATES = {"ceo_approved", "independently_verified", "merged_source"}
PENDING_STATES = {"builder_report", "pending", "unresolved"}
EVENT_ID_RE = re.compile(r"EVT-\d{8}-\d{3,}")
SHA_RE = re.compile(r"^[0-9a-f]{40}$")
SECRET_PATTERNS = (
    re.compile(r"\bsk-[A-Za-z0-9]{20,}\b"),
    re.compile(r"\bgh[pousr]_[A-Za-z0-9]{20,}\b"),
    re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
    re.compile(r"(?i)bearer\s+[A-Za-z0-9._-]{24,}"),
)
V1_GENERATED_MARKER = "<!-- GENERATED BY SportsBrainMemory V1: DO NOT EDIT -->"
V2_GENERATED_MARKER = "<!-- GENERATED BY SportsBrainMemory V2: DO NOT EDIT -->"


class MemoryV2Error(ValueError):
    """Raised when an update cannot be accepted without guessing."""


@dataclass(frozen=True)
class IngestResult:
    event_id: str
    destination: str
    changed: bool


def now_utc() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def parse_timestamp(value: Any, field: str = "timestamp") -> datetime:
    if not isinstance(value, str) or not value.strip():
        raise MemoryV2Error(f"{field} must be an ISO-8601 timestamp")
    try:
        parsed = datetime.fromisoformat(value.strip().replace("Z", "+00:00"))
    except ValueError as exc:
        raise MemoryV2Error(f"{field} is not a valid ISO-8601 timestamp: {value!r}") from exc
    if parsed.tzinfo is None:
        raise MemoryV2Error(f"{field} must include a timezone: {value!r}")
    return parsed.astimezone(timezone.utc)


def _scan_for_secrets(value: Any, path: str = "event") -> None:
    if isinstance(value, dict):
        for key, child in value.items():
            _scan_for_secrets(child, f"{path}.{key}")
    elif isinstance(value, list):
        for index, child in enumerate(value):
            _scan_for_secrets(child, f"{path}[{index}]")
    elif isinstance(value, str) and any(pattern.search(value) for pattern in SECRET_PATTERNS):
        raise MemoryV2Error(f"secret-like material detected at {path}")


def validate_event(event: dict[str, Any], *, canonical: bool | None = None) -> dict[str, Any]:
    if not isinstance(event, dict):
        raise MemoryV2Error("event must be an object")
    required = {
        "event_id", "timestamp", "type", "domain", "summary", "source_repository",
        "builder", "ceo_gate_state", "affected_workstreams", "findings", "invariants",
        "supersedes", "evidence", "verification_state",
    }
    missing = sorted(required - set(event))
    if missing:
        raise MemoryV2Error(f"event missing required field(s): {', '.join(missing)}")
    event_id = event["event_id"]
    if not isinstance(event_id, str) or not EVENT_ID_RE.fullmatch(event_id):
        raise MemoryV2Error(f"event_id must match EVT-YYYYMMDD-NNN: {event_id!r}")
    parse_timestamp(event["timestamp"])
    if event["type"] not in EVENT_TYPES:
        raise MemoryV2Error(f"unsupported event type: {event['type']!r}")
    for field in ("domain", "summary", "source_repository", "builder", "ceo_gate_state", "verification_state"):
        if not isinstance(event[field], str) or not event[field].strip():
            raise MemoryV2Error(f"event field {field!r} must be a non-empty string")
    for field in ("affected_workstreams", "findings", "invariants", "supersedes", "evidence"):
        if not isinstance(event[field], list) or not all(isinstance(item, str) for item in event[field]):
            raise MemoryV2Error(f"event field {field!r} must be a list of strings")
    source_sha = event.get("source_sha")
    if source_sha is not None and (not isinstance(source_sha, str) or not SHA_RE.fullmatch(source_sha)):
        raise MemoryV2Error("source_sha must be a 40-character lowercase Git SHA when present")
    source_pr = event.get("source_pr")
    if source_pr is not None and (not isinstance(source_pr, int) or source_pr < 1):
        raise MemoryV2Error("source_pr must be a positive integer when present")
    is_canonical = bool(event.get("canonical", canonical if canonical is not None else False))
    state = event["verification_state"]
    if is_canonical and state not in VERIFIED_STATES:
        raise MemoryV2Error(f"canonical event {event_id} requires verified state; got {state!r}")
    if not is_canonical and state not in VERIFIED_STATES | PENDING_STATES:
        raise MemoryV2Error(f"unknown verification_state: {state!r}")
    if state == "builder_report" and is_canonical:
        raise MemoryV2Error("builder reports cannot be canonical without CEO or independent verification")
    _scan_for_secrets(event)
    normalized = json.loads(json.dumps(event, sort_keys=True, ensure_ascii=False))
    normalized["canonical"] = is_canonical
    return normalized


def _safe_relative(root: Path, rel: str) -> Path:
    if not isinstance(rel, str) or not rel or rel.startswith("/"):
        raise MemoryV2Error(f"invalid relative path: {rel!r}")
    target = (root / rel).resolve()
    root_resolved = root.resolve()
    if target != root_resolved and root_resolved not in target.parents:
        raise MemoryV2Error(f"path escapes Memory repository: {rel!r}")
    return target


def _event_path(root: Path, event_id: str, canonical: bool) -> Path:
    return root / "events" / ("records" if canonical else "pending") / f"{event_id}.json"


def _existing_event(root: Path, event_id: str) -> tuple[Path, dict[str, Any]] | None:
    for path in (_event_path(root, event_id, True), _event_path(root, event_id, False)):
        if path.exists():
            try:
                return path, json.loads(path.read_text(encoding="utf-8"))
            except json.JSONDecodeError as exc:
                raise MemoryV2Error(f"existing event is invalid JSON: {path}") from exc
    return None


def _write_json_atomic(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent, delete=False) as handle:
        json.dump(payload, handle, indent=2, sort_keys=True, ensure_ascii=False)
        handle.write("\n")
        temporary = Path(handle.name)
    temporary.replace(path)


def ingest_events(root: Path, events: list[dict[str, Any]], *, canonical_records: list[dict[str, str]] | None = None, validate_after: bool = True) -> list[IngestResult]:
    """Apply events and optional canonical record writes transactionally."""
    if not isinstance(events, list) or not events:
        raise MemoryV2Error("events must be a non-empty list")
    normalized = [validate_event(event) for event in events]
    ids = [event["event_id"] for event in normalized]
    if len(ids) != len(set(ids)):
        raise MemoryV2Error("duplicate event_id in update payload")
    records = canonical_records or []
    for record in records:
        path = _safe_relative(root, record.get("path"))
        rel = path.relative_to(root).as_posix()
        allowed = ("decisions/records/", "workstreams/", "tasks/records/", "findings/records/", "architecture/", "history/", "state/records/", "_meta/", "builder/", "events/")
        if not rel.startswith(allowed):
            raise MemoryV2Error(f"canonical record path is outside approved Memory namespaces: {rel}")
        if not isinstance(record.get("content"), str):
            raise MemoryV2Error(f"canonical record content must be text: {rel}")
        _scan_for_secrets(record["content"], rel)
    touched: list[tuple[Path, bytes | None]] = []
    results: list[IngestResult] = []
    try:
        for event in normalized:
            existing = _existing_event(root, event["event_id"])
            if existing:
                old_path, old_payload = existing
                if old_payload != event:
                    raise MemoryV2Error(f"event_id already exists with a different payload: {event['event_id']}")
                results.append(IngestResult(event["event_id"], old_path.relative_to(root).as_posix(), False))
                continue
            path = _event_path(root, event["event_id"], bool(event["canonical"]))
            touched.append((path, path.read_bytes() if path.exists() else None))
            _write_json_atomic(path, event)
            results.append(IngestResult(event["event_id"], path.relative_to(root).as_posix(), True))
        for record in records:
            path = _safe_relative(root, record["path"])
            touched.append((path, path.read_bytes() if path.exists() else None))
            path.parent.mkdir(parents=True, exist_ok=True)
            temporary = path.with_suffix(path.suffix + ".tmp")
            temporary.write_text(record["content"].rstrip() + "\n", encoding="utf-8")
            temporary.replace(path)
        if validate_after:
            from .validate import validate
            report = validate(root, "v1")
            if report.errors:
                raise MemoryV2Error(f"post-update validation failed with {report.errors} error(s)")
    except Exception:
        for path, old in reversed(touched):
            if old is None:
                path.unlink(missing_ok=True)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(old)
        raise
    return results


def read_manifest(root: Path) -> dict[str, Any]:
    path = root / "_meta" / "MEMORY_V2.json"
    if not path.exists():
        raise MemoryV2Error("_meta/MEMORY_V2.json is missing")
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise MemoryV2Error("_meta/MEMORY_V2.json is invalid JSON") from exc
    if value.get("memory_version") != 2:
        raise MemoryV2Error("MEMORY_V2.json does not declare memory_version=2")
    return value


def freshness_state(canonical_updated_at: str, source_meaningful_at: str, *, aging_hours: float = 6.0, stale_hours: float = 24.0) -> str:
    canonical = parse_timestamp(canonical_updated_at, "canonical_updated_at")
    source = parse_timestamp(source_meaningful_at, "source_meaningful_at")
    lag_hours = max(0.0, (source - canonical).total_seconds() / 3600.0)
    if lag_hours > stale_hours:
        return "STALE"
    if lag_hours > aging_hours:
        return "AGING"
    return "FRESH"


def file_sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


